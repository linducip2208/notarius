-- 003_deeds.sql — deeds, repertorium, protocols, legalization, wills, templates, clauses
CREATE TABLE IF NOT EXISTS deed_drafts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  office_id BIGINT UNSIGNED NOT NULL,
  request_id BIGINT UNSIGNED NULL,
  number VARCHAR(50) NULL,
  title VARCHAR(255) NOT NULL,
  kind ENUM('PT','CV','Yayasan','Agreement','Will','POA','Prenup','Other') NOT NULL DEFAULT 'Other',
  status ENUM('DRAFT','IN_REVIEW','APPROVED','SIGNED','ARCHIVED') NOT NULL DEFAULT 'DRAFT',
  template_id BIGINT UNSIGNED NULL,
  version INT NOT NULL DEFAULT 1,
  content MEDIUMTEXT NULL,
  content_hash CHAR(16) NULL,
  locked TINYINT(1) NOT NULL DEFAULT 0,
  created_by BIGINT UNSIGNED NULL,
  approved_by BIGINT UNSIGNED NULL,
  approved_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (office_id) REFERENCES offices(id) ON DELETE RESTRICT,
  UNIQUE KEY uq_deed_number (office_id, number),
  INDEX idx_deed_status (status)
);

CREATE TABLE IF NOT EXISTS deed_versions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  deed_id BIGINT UNSIGNED NOT NULL,
  version INT NOT NULL,
  content MEDIUMTEXT NOT NULL,
  content_hash CHAR(16) NOT NULL,
  created_by BIGINT UNSIGNED NULL,
  note VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (deed_id) REFERENCES deed_drafts(id) ON DELETE CASCADE,
  UNIQUE KEY uq_deed_ver (deed_id, version)
);

CREATE TABLE IF NOT EXISTS repertorium (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  office_id BIGINT UNSIGNED NOT NULL,
  entry_no BIGINT UNSIGNED NOT NULL,
  entry_date DATE NOT NULL,
  deed_id BIGINT UNSIGNED NULL,
  description VARCHAR(500) NOT NULL,
  parties VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (office_id) REFERENCES offices(id) ON DELETE RESTRICT,
  FOREIGN KEY (deed_id) REFERENCES deed_drafts(id) ON DELETE SET NULL,
  UNIQUE KEY uq_repert (office_id, entry_no)
);

CREATE TABLE IF NOT EXISTS protocols (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  office_id BIGINT UNSIGNED NOT NULL,
  bundle_no VARCHAR(50) NOT NULL,
  year INT NOT NULL,
  deed_id BIGINT UNSIGNED NULL,
  minuta_ref VARCHAR(255) NULL,
  handover_note TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (office_id) REFERENCES offices(id) ON DELETE RESTRICT,
  UNIQUE KEY uq_protocol (office_id, bundle_no, year)
);

CREATE TABLE IF NOT EXISTS legalizations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  office_id BIGINT UNSIGNED NOT NULL,
  kind ENUM('LEGALISASI','WAARMERKING','SALINAN','KUTIPAN') NOT NULL,
  register_no VARCHAR(50) NOT NULL,
  client_id BIGINT UNSIGNED NOT NULL,
  doc_title VARCHAR(255) NOT NULL,
  fee DECIMAL(18,2) NOT NULL DEFAULT 0,
  status ENUM('REGISTERED','COMPLETED','HANDED_OVER') NOT NULL DEFAULT 'REGISTERED',
  completed_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (office_id) REFERENCES offices(id) ON DELETE RESTRICT,
  FOREIGN KEY (client_id) REFERENCES clients(id) ON DELETE RESTRICT,
  UNIQUE KEY uq_leg (office_id, kind, register_no)
);

CREATE TABLE IF NOT EXISTS wills (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  office_id BIGINT UNSIGNED NOT NULL,
  client_id BIGINT UNSIGNED NOT NULL,
  deed_id BIGINT UNSIGNED NULL,
  register_no VARCHAR(50) NULL,
  status ENUM('DRAFT','REGISTERED','ARCHIVED') NOT NULL DEFAULT 'DRAFT',
  restricted TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (office_id) REFERENCES offices(id) ON DELETE RESTRICT,
  FOREIGN KEY (client_id) REFERENCES clients(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS doc_templates (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  office_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(255) NOT NULL,
  category VARCHAR(100) NOT NULL,
  body MEDIUMTEXT NOT NULL,
  version INT NOT NULL DEFAULT 1,
  approved TINYINT(1) NOT NULL DEFAULT 0,
  approved_by BIGINT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (office_id) REFERENCES offices(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS clauses (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  office_id BIGINT UNSIGNED NOT NULL,
  title VARCHAR(255) NOT NULL,
  body TEXT NOT NULL,
  tags VARCHAR(255) NULL,
  approved TINYINT(1) NOT NULL DEFAULT 0,
  FOREIGN KEY (office_id) REFERENCES offices(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS approvals (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  entity VARCHAR(50) NOT NULL,
  entity_id BIGINT UNSIGNED NOT NULL,
  requested_by BIGINT UNSIGNED NULL,
  decided_by BIGINT UNSIGNED NULL,
  decision ENUM('PENDING','APPROVED','REJECTED') NOT NULL DEFAULT 'PENDING',
  note VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  decided_at TIMESTAMP NULL,
  INDEX idx_approvals_entity (entity, entity_id)
);

CREATE TABLE IF NOT EXISTS signatures (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  deed_id BIGINT UNSIGNED NOT NULL,
  signer_name VARCHAR(255) NOT NULL,
  signer_role VARCHAR(100) NULL,
  signed_at TIMESTAMP NULL,
  method VARCHAR(50) NOT NULL DEFAULT 'wet',
  FOREIGN KEY (deed_id) REFERENCES deed_drafts(id) ON DELETE CASCADE
);
