-- 011_dms.sql — enterprise document lifecycle (metadata MySQL, binari tetap privat).
-- Tidak menyentuh tabel lama selain ADD COLUMN; semua baru IF NOT EXISTS.
ALTER TABLE files
  ADD COLUMN category_id BIGINT UNSIGNED NULL,
  ADD COLUMN doc_number VARCHAR(100) NULL,
  ADD COLUMN display_name VARCHAR(255) NULL,
  ADD COLUMN doc_date DATE NULL,
  ADD COLUMN expiry_date DATE NULL,
  ADD COLUMN verification_status ENUM('UNVERIFIED','PENDING','VERIFIED','REJECTED') NOT NULL DEFAULT 'UNVERIFIED',
  ADD COLUMN workflow_status ENUM('RECEIVED','CLASSIFICATION','ADMIN_REVIEW','VERIFICATION','REVISION_REQUIRED','APPROVAL','APPROVED','FINALIZED','ARCHIVED','REJECTED') NOT NULL DEFAULT 'RECEIVED',
  ADD COLUMN confidentiality ENUM('PUBLIC','INTERNAL','CONFIDENTIAL','RESTRICTED') NOT NULL DEFAULT 'INTERNAL';

CREATE TABLE IF NOT EXISTS doc_categories (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  office_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(100) NOT NULL,
  description VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (office_id) REFERENCES offices(id) ON DELETE CASCADE,
  UNIQUE KEY uq_doccat (office_id, name)
);

ALTER TABLE files ADD CONSTRAINT fk_files_category
  FOREIGN KEY (category_id) REFERENCES doc_categories(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS doc_versions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  file_id BIGINT UNSIGNED NOT NULL,
  version_no INT NOT NULL,
  ref VARCHAR(512) NOT NULL,
  sha256 CHAR(64) NOT NULL,
  size_bytes BIGINT NOT NULL,
  note VARCHAR(500) NULL,
  created_by BIGINT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (file_id) REFERENCES files(id) ON DELETE CASCADE,
  UNIQUE KEY uq_docver (file_id, version_no)
);

CREATE TABLE IF NOT EXISTS doc_relations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  file_id BIGINT UNSIGNED NOT NULL,
  related_type ENUM('client','request','deed','repertorium','will','legalization','invoice','service','company') NOT NULL,
  related_id BIGINT UNSIGNED NOT NULL,
  relation VARCHAR(100) NOT NULL DEFAULT 'lampiran',
  created_by BIGINT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (file_id) REFERENCES files(id) ON DELETE CASCADE,
  INDEX idx_docrel (related_type, related_id)
);

CREATE TABLE IF NOT EXISTS doc_workflow_events (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  file_id BIGINT UNSIGNED NOT NULL,
  actor_id BIGINT UNSIGNED NULL,
  from_status VARCHAR(30) NULL,
  to_status VARCHAR(30) NOT NULL,
  note VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (file_id) REFERENCES files(id) ON DELETE CASCADE,
  INDEX idx_docwf (file_id)
);

CREATE TABLE IF NOT EXISTS doc_ocr_jobs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  file_id BIGINT UNSIGNED NOT NULL,
  status ENUM('QUEUED','RUNNING','DONE','FAILED') NOT NULL DEFAULT 'QUEUED',
  attempts INT NOT NULL DEFAULT 0,
  last_error VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (file_id) REFERENCES files(id) ON DELETE CASCADE,
  INDEX idx_ocrjob (status, updated_at)
);

CREATE TABLE IF NOT EXISTS doc_search_index (
  file_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
  content MEDIUMTEXT NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FULLTEXT INDEX ft_docsearch (content),
  FOREIGN KEY (file_id) REFERENCES files(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS doc_favorites (
  user_id BIGINT UNSIGNED NOT NULL,
  file_id BIGINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, file_id),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (file_id) REFERENCES files(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS doc_shares (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  file_id BIGINT UNSIGNED NOT NULL,
  token CHAR(32) NOT NULL UNIQUE,
  expires_at TIMESTAMP NOT NULL,
  max_downloads INT NOT NULL DEFAULT 5,
  downloads INT NOT NULL DEFAULT 0,
  revoked TINYINT(1) NOT NULL DEFAULT 0,
  created_by BIGINT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (file_id) REFERENCES files(id) ON DELETE CASCADE,
  INDEX idx_share_tok (token)
);

CREATE TABLE IF NOT EXISTS doc_archive_locations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  office_id BIGINT UNSIGNED NOT NULL,
  code VARCHAR(50) NOT NULL,
  room VARCHAR(100) NULL,
  shelf VARCHAR(100) NULL,
  box VARCHAR(100) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (office_id) REFERENCES offices(id) ON DELETE CASCADE,
  UNIQUE KEY uq_arcloc (office_id, code)
);

CREATE TABLE IF NOT EXISTS doc_archive_movements (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  file_id BIGINT UNSIGNED NOT NULL,
  location_id BIGINT UNSIGNED NULL,
  movement ENUM('STORE','RETRIEVE','RETURN','TRANSFER') NOT NULL,
  actor_id BIGINT UNSIGNED NULL,
  note VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (file_id) REFERENCES files(id) ON DELETE CASCADE,
  FOREIGN KEY (location_id) REFERENCES doc_archive_locations(id) ON DELETE SET NULL,
  INDEX idx_docmove (file_id)
);

CREATE TABLE IF NOT EXISTS doc_legal_holds (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  file_id BIGINT UNSIGNED NOT NULL,
  office_id BIGINT UNSIGNED NOT NULL,
  reason VARCHAR(500) NOT NULL,
  applied_by BIGINT UNSIGNED NULL,
  applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  released_at TIMESTAMP NULL,
  FOREIGN KEY (file_id) REFERENCES files(id) ON DELETE CASCADE,
  INDEX idx_hold (file_id, released_at)
);

CREATE TABLE IF NOT EXISTS doc_dispositions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  file_id BIGINT UNSIGNED NOT NULL,
  office_id BIGINT UNSIGNED NOT NULL,
  action ENUM('RETAIN','DESTROY_REQUEST','DESTROYED') NOT NULL,
  decided_by BIGINT UNSIGNED NULL,
  note VARCHAR(500) NULL,
  decided_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (file_id) REFERENCES files(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS doc_access_logs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  file_id BIGINT UNSIGNED NOT NULL,
  user_id BIGINT UNSIGNED NULL,
  action ENUM('VIEW','PREVIEW','DOWNLOAD','SHARE','PRINT') NOT NULL,
  ip VARCHAR(64) NULL,
  user_agent VARCHAR(500) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (file_id) REFERENCES files(id) ON DELETE CASCADE,
  INDEX idx_access (file_id, created_at)
);

CREATE TABLE IF NOT EXISTS doc_checklist_templates (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  office_id BIGINT UNSIGNED NOT NULL,
  service_code VARCHAR(50) NULL,
  name VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (office_id) REFERENCES offices(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS doc_checklist_items (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  template_id BIGINT UNSIGNED NOT NULL,
  label VARCHAR(255) NOT NULL,
  is_required TINYINT(1) NOT NULL DEFAULT 1,
  FOREIGN KEY (template_id) REFERENCES doc_checklist_templates(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS doc_checklist_records (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  office_id BIGINT UNSIGNED NOT NULL,
  request_id BIGINT UNSIGNED NOT NULL,
  item_id BIGINT UNSIGNED NOT NULL,
  status ENUM('MISSING','RECEIVED','VERIFIED','REJECTED','NEEDS_REVISION') NOT NULL DEFAULT 'MISSING',
  verified_by BIGINT UNSIGNED NULL,
  verified_at TIMESTAMP NULL,
  note VARCHAR(500) NULL,
  FOREIGN KEY (request_id) REFERENCES service_requests(id) ON DELETE CASCADE,
  FOREIGN KEY (item_id) REFERENCES doc_checklist_items(id) ON DELETE CASCADE,
  UNIQUE KEY uq_checkrec (request_id, item_id)
);
